def get_preset(preset_id: str) -> tuple[str, dict] | None:
    """Возвращает (название мода, словарь стран) или None."""
    return PRESETS.get(preset_id.lower())


def get_all_countries(preset: dict) -> list[tuple[str, int]]:
    """Возвращает плоский список всех стран (название, слотов) из пресета."""
    result = []
    for faction_countries in preset.values():
        result.extend(faction_countries)
    return result
